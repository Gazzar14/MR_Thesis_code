apply_gt_formatting <- function(data, is_grouped = FALSE) {
  
  if (is_grouped) {
    # Grouping logic
    tbl <- data %>%
      arrange(instrument, desc(max_value)) %>%
      group_by(instrument) %>%
      gt() %>%
      tab_options(
        row_group.background.color = "#f0f0f0",
        row_group.font.weight = "bold"
      )
  } else {
    # Standard logic
    tbl <- data %>% gt()
  }
  
  # Apply labels and colors to all tables
  tbl <- tbl %>%
    cols_label(
      exposure = "Exposure (Vit D)",
      outcome = "Outcome (MetS)",
      instrument_levels = "IV Levels",
      x_levels = "Exp. Levels",
      y_levels = "Out. Levels",
      max_value = "Max Value",
      violated = "Violated"
    ) %>%
    data_color(
      columns = violated,
      target_columns = everything(),
      fn = scales::col_factor(palette = c("white", "#ffe6e6"), domain = c(FALSE, TRUE))
    )
  
  # Add the instrument label back if it's not grouped
  if (!is_grouped) {
    tbl <- tbl %>% cols_label(instrument = "Instrument")
  }
  
  return(tbl)
}

