# Visualising Exposure Discretization

plot_discretization_heatmap <- function(
    summary_tbl,
    outcome_var,
    exposure_seq,
    joint_type = "combination",
    reference_exposure = NULL,
    relative = FALSE
) {
  
  joint_instrument <- if (joint_type == "combination") {
    "snp_combination"
  } else {
    "snp_additive"
  }
  
  # ---------------------------------------------------------
  # 1. Select relevant instruments
  # ---------------------------------------------------------
  
  instrument_order <- c(
    "rs11732044_t",
    "rs116970203_a",
    joint_instrument
  )
  
  instrument_labels <- c(
    "rs11732044_t" = "SNP 1",
    "rs116970203_a" = "SNP 2",
    "snp_combination" = "Joint",
    "snp_additive" = "Joint"
  )
  
  # ---------------------------------------------------------
  # 2. Extract data
  # ---------------------------------------------------------
  
  plot_data <- summary_tbl %>%
    filter(
      outcome == outcome_var,
      exposure %in% exposure_seq,
      instrument %in% instrument_order
    ) %>%
    mutate(
      exposure = factor(exposure, levels = exposure_seq),
      instrument = factor(
        instrument,
        levels = instrument_order
      ),
      instrument_label = case_when(
        as.character(instrument) == "rs11732044_t" ~ "SNP 1",
        as.character(instrument) == "rs116970203_a" ~ "SNP 2",
        as.character(instrument) %in% c(
          "snp_combination",
          "snp_additive"
        ) ~ "Joint",
        TRUE ~ as.character(instrument)
      )
    ) %>%
    select(
      exposure,
      x_levels,
      instrument,
      instrument_label,
      max_value
    ) %>%
    distinct()
  
  # ---------------------------------------------------------
  # 3. Calculate values
  # ---------------------------------------------------------
  
  if (relative) {
    
    if (is.null(reference_exposure)) {
      reference_exposure <- exposure_seq[1]
    }
    
    reference_values <- plot_data %>%
      filter(exposure == reference_exposure) %>%
      select(
        instrument,
        reference_value = max_value
      )
    
    plot_data <- plot_data %>%
      left_join(
        reference_values,
        by = "instrument"
      ) %>%
      mutate(
        value = max_value - reference_value
      )
    
  } else {
    
    plot_data <- plot_data %>%
      mutate(value = max_value)
  }
  
  # ---------------------------------------------------------
  # 4. Exposure labels
  # ---------------------------------------------------------
  
  exposure_labels <- plot_data %>%
    distinct(exposure, x_levels) %>%
    mutate(
      label = paste0(
        as.character(exposure),
        "\n(",
        x_levels,
        " categories)"
      )
    )
  
  x_labels <- exposure_labels$label
  names(x_labels) <- exposure_labels$exposure
  
  # ---------------------------------------------------------
  # 5. Absolute heatmap
  # ---------------------------------------------------------
  
  if (!relative) {
    
    # Maximum value in the actual data
    data_max <- max(plot_data$value, na.rm = TRUE)
    
    # Keep the upper limit at least 1, but allow values > 1
    scale_max <- max(1, data_max)
    
    p <- ggplot(
      plot_data,
      aes(
        x = exposure,
        y = instrument_label,
        fill = value
      )
    ) +
      
      geom_tile(
        colour = "white",
        linewidth = 0.8
      ) +
      
      # Values >= 1 are red; values < 1 are white
      geom_text(
        aes(
          label = sprintf("%.2f", value),
          colour = value >= 1
        ),
        size = 3.5,
        fontface = "bold"
      ) +
      
      scale_colour_manual(
        values = c(
          "FALSE" = "white",
          "TRUE" = "red"
        ),
        guide = "none"
      ) +
      
      # Light = low inequality
      # Dark = high inequality
      scale_fill_gradient(
        low = "grey95",
        high = "grey25",
        limits = c(0, scale_max),
        breaks = pretty(c(0, scale_max)),
        name = "Maximum\ninequality"
      ) +
      
      labs(
        x = NULL,
        y = NULL,
        title = paste0(
          outcome_var,
          " — ",
          joint_type,
          " instrument"
        )
      )
    
  } else {
    
    # -------------------------------------------------------
    # Relative / sensitivity heatmap
    # -------------------------------------------------------
    
    max_abs <- max(abs(plot_data$value), na.rm = TRUE)
    
    p <- ggplot(
      plot_data,
      aes(
        x = exposure,
        y = instrument_label,
        fill = value
      )
    ) +
      
      geom_tile(
        colour = "white",
        linewidth = 0.8
      ) +
      
      geom_text(
        aes(
          label = sprintf("%.2f", value),
          colour = value > 0
        ),
        size = 3.5,
        fontface = "bold"
      ) +
      
      scale_colour_manual(
        values = c(
          "FALSE" = "white",
          "TRUE" = "red"
        ),
        guide = "none"
      ) +
      
      scale_fill_gradient2(
        low = "grey80",
        mid = "white",
        high = "grey25",
        midpoint = 0,
        limits = c(-max_abs, max_abs),
        name = "Change in\nmax inequality"
      ) +
      
      labs(
        x = NULL,
        y = NULL,
        title = paste0(
          outcome_var,
          " — ",
          joint_type,
          " instrument"
        ),
        subtitle = "Change relative to reference discretisation"
      )
  }
  
  # ---------------------------------------------------------
  # 6. Final formatting
  # ---------------------------------------------------------
  
  p +
    scale_x_discrete(
      labels = x_labels
    ) +
    
    theme_minimal(base_size = 11) +
    
    theme(
      panel.grid = element_blank(),
      
      axis.text.x = element_text(
        angle = 0,
        hjust = 0.5
      ),
      
      axis.text.y = element_text(
        face = "bold"
      ),
      
      plot.title = element_text(
        face = "bold"
      ),
      
      plot.subtitle = element_text(
        size = 9
      ),
      
      legend.position = "right"
    )
}

